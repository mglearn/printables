/* Gallery logic for the Phase Change Station Lab collection.
   Reads window.PCS_MANIFEST (generated by build-manifest.sh), renders the seven
   stations in lab order, and offers PNG + PDF download plus a lightbox preview.
   Unlike the refusal-form gallery there are no categories — the stations run as a
   single 1 -> 7 sequence — so this is a trimmed version of that app. */
(function () {
  'use strict';

  var M = window.PCS_MANIFEST || [];

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }

  function render() {
    var grid = document.getElementById('gallery');
    var count = document.getElementById('gallery-count');
    if (count) count.textContent = M.length + (M.length === 1 ? ' station' : ' stations');

    grid.innerHTML = '';
    if (!M.length) {
      grid.appendChild(el('p', 'empty', 'No stations yet.'));
      return;
    }
    var row = el('div', 'row');
    M.forEach(function (w) { row.appendChild(card(w)); });
    grid.appendChild(row);
  }

  function card(w) {
    var fig = el('figure', 'card');

    var btn = el('button', 'thumb');
    btn.type = 'button';
    btn.setAttribute('aria-label', 'Preview ' + w.title);
    var img = el('img');
    img.loading = 'lazy';
    img.src = w.file;
    img.alt = 'Station ' + w.station + ': ' + w.title + ' — printable phase change station sheet';
    btn.appendChild(img);
    btn.addEventListener('click', function () { openLightbox(w); });
    fig.appendChild(btn);

    var cap = el('figcaption');
    cap.appendChild(el('span', 'card-title', 'Station ' + w.station + ': ' + w.title));
    if (w.transition) cap.appendChild(el('span', 'card-tag', w.transition));
    if (w.focus) cap.appendChild(el('span', 'card-focus', w.focus));

    var dls = el('span', 'card-dls');
    dls.appendChild(dl(w.file, '↓ PNG', 'Download ' + w.title + ' as PNG'));
    if (w.pdf) dls.appendChild(dl(w.pdf, '↓ PDF', 'Download ' + w.title + ' as a print-ready PDF'));
    cap.appendChild(dls);

    fig.appendChild(cap);
    return fig;
  }

  function dl(href, text, label) {
    var a = el('a', 'card-dl', text);
    a.href = href;
    a.setAttribute('download', '');
    a.setAttribute('aria-label', label);
    a.title = label;
    return a;
  }

  // --- Lightbox ---
  function openLightbox(w) {
    var lb = document.getElementById('lightbox');
    var img = document.getElementById('lightbox-img');
    var dlPng = document.getElementById('lightbox-dl-png');
    var dlPdf = document.getElementById('lightbox-dl-pdf');
    img.src = w.file;
    img.alt = w.title;
    dlPng.href = w.file;
    if (w.pdf) { dlPdf.href = w.pdf; dlPdf.style.display = ''; }
    else { dlPdf.style.display = 'none'; }
    lb.classList.add('open');
    lb.setAttribute('aria-hidden', 'false');
    document.getElementById('lightbox-close').focus();
  }
  function closeLightbox() {
    var lb = document.getElementById('lightbox');
    lb.classList.remove('open');
    lb.setAttribute('aria-hidden', 'true');
    document.getElementById('lightbox-img').src = '';
  }

  function init() {
    document.getElementById('lightbox-close').addEventListener('click', closeLightbox);
    document.getElementById('lightbox').addEventListener('click', function (e) {
      if (e.target.id === 'lightbox') closeLightbox();
    });
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape') closeLightbox();
    });
    render();
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
