/* Gallery logic for the Student Refusal Forms collection.
   Reads window.SRF_MANIFEST (generated by build-manifest.sh), renders cards
   grouped by category, and offers PNG + PDF download plus a lightbox preview. */
(function () {
  'use strict';

  var M = window.SRF_MANIFEST || [];

  // Category display order + labels.
  var CATEGORIES = [
    { key: 'tech',    label: 'Tech & Internet' },
    { key: 'social',  label: 'Social Media & Memes' },
    { key: 'games',   label: 'Games, Sports & Challenges' },
    { key: 'content', label: 'Content-Area Reflections' }
  ];
  var CAT_LABEL = {};
  CATEGORIES.forEach(function (c) { CAT_LABEL[c.key] = c.label; });
  var CAT_ORDER = CATEGORIES.map(function (c) { return c.key; });

  var state = { category: 'all' };

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }

  function render() {
    var grid = document.getElementById('gallery');
    var count = document.getElementById('gallery-count');

    var items = M.filter(function (w) {
      return state.category === 'all' || w.category === state.category;
    });
    items.sort(function (a, b) {
      var d = CAT_ORDER.indexOf(a.category) - CAT_ORDER.indexOf(b.category);
      if (d) return d;
      return M.indexOf(a) - M.indexOf(b); // preserve manifest order within a category
    });

    count.textContent = items.length + (items.length === 1 ? ' form' : ' forms');

    grid.innerHTML = '';
    if (!items.length) {
      grid.appendChild(el('p', 'empty', 'No forms in this category yet.'));
      return;
    }

    var lastCat = null, row = null;
    items.forEach(function (w) {
      if (w.category !== lastCat) {
        lastCat = w.category;
        grid.appendChild(el('h3', 'group-head', CAT_LABEL[w.category] || w.category));
        row = el('div', 'row');
        grid.appendChild(row);
      }
      row.appendChild(card(w));
    });
  }

  function card(w) {
    var fig = el('figure', 'card');

    var btn = el('button', 'thumb');
    btn.type = 'button';
    btn.setAttribute('aria-label', 'Preview ' + w.title);
    var img = el('img');
    img.loading = 'lazy';
    img.src = w.file;
    img.alt = w.title + ' — student refusal reflection form';
    btn.appendChild(img);
    btn.addEventListener('click', function () { openLightbox(w); });
    fig.appendChild(btn);

    var cap = el('figcaption');
    cap.appendChild(el('span', 'card-title', w.title));

    var dls = el('span', 'card-dls');
    dls.appendChild(dl(w.file, '↓ PNG', 'Download ' + w.title + ' as PNG'));
    if (w.pdf) dls.appendChild(dl(w.pdf, '↓ PDF', 'Download ' + w.title + ' as a print-ready PDF'));
    cap.appendChild(dls);

    fig.appendChild(cap);
    return fig;
  }

  function dl(href, text, label) {
    var a = el('a', 'card-dl', text);
    a.href = href;
    a.setAttribute('download', '');
    a.setAttribute('aria-label', label);
    a.title = label;
    return a;
  }

  // --- Lightbox ---
  function openLightbox(w) {
    var lb = document.getElementById('lightbox');
    var img = document.getElementById('lightbox-img');
    var dlPng = document.getElementById('lightbox-dl-png');
    var dlPdf = document.getElementById('lightbox-dl-pdf');
    img.src = w.file;
    img.alt = w.title;
    dlPng.href = w.file;
    if (w.pdf) { dlPdf.href = w.pdf; dlPdf.style.display = ''; }
    else { dlPdf.style.display = 'none'; }
    lb.classList.add('open');
    lb.setAttribute('aria-hidden', 'false');
    document.getElementById('lightbox-close').focus();
  }
  function closeLightbox() {
    var lb = document.getElementById('lightbox');
    lb.classList.remove('open');
    lb.setAttribute('aria-hidden', 'true');
    document.getElementById('lightbox-img').src = '';
  }

  function init() {
    var sel = document.getElementById('filter-category');
    var optAll = el('option', null, 'All categories');
    optAll.value = 'all';
    sel.appendChild(optAll);
    CATEGORIES.forEach(function (c) {
      if (!M.some(function (w) { return w.category === c.key; })) return;
      var o = el('option', null, c.label);
      o.value = c.key;
      sel.appendChild(o);
    });
    sel.addEventListener('change', function () { state.category = sel.value; render(); });
    document.getElementById('filter-reset').addEventListener('click', function () {
      state.category = 'all'; sel.value = 'all'; render();
    });

    document.getElementById('lightbox-close').addEventListener('click', closeLightbox);
    document.getElementById('lightbox').addEventListener('click', function (e) {
      if (e.target.id === 'lightbox') closeLightbox();
    });
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape') closeLightbox();
    });

    render();
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
